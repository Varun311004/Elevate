export function getCurriculumTopics(
  grade,
  subject,
  difficulty = "adaptive"
) {
  const subjectData =
    STEM_CURRICULUM?.[grade]?.[subject];

  if (!subjectData) {
    return [];
  }

  if (
    difficulty
    && difficulty !== "adaptive"
    && subjectData[difficulty]
  ) {
    return [
      ...subjectData[difficulty]
    ];
  }

  return [
    ...new Set(
      Object.values(
        subjectData
      ).flat()
    )
  ];
}